import { api } from '../../shared/api';
import type { AgeBand, GenerateWorldResponse, LessonSpec, Material, Question, TemplateId, WorldSpec, Zone } from '../../shared/contracts';
import { I, iso, islandSVG } from '../art';
import { $, $$, confetti, esc, friendly, hydrateThumbs, playUrl, reducedMotion, thumb, toast, WORLDS, worldMeta } from '../ui';

type Sample = Awaited<ReturnType<typeof api.samples>>[number];
type SourceTab = 'pdf' | 'text';

interface State {
  tab: SourceTab;
  material?: Material;
  lesson?: LessonSpec;
  lessonSource?: string;
  lessonDiag?: string[];
  ageBand: AgeBand;
  template?: TemplateId;
  gen?: GenerateWorldResponse;
  world?: WorldSpec;
  dirty?: boolean;
  savedDiag?: string[];
  err?: { at: 'source' | 'lesson' | 'world' | 'save'; msg: string; retry?: () => void };
  busy?: 'source' | 'lesson' | 'world' | 'save';
}

const KEY = 'wc-lab-v1';
const load = (): State => { try { const s = JSON.parse(sessionStorage.getItem(KEY) ?? 'null'); if (s) return { ...s, busy: undefined, err: undefined }; } catch { /* */ } return { tab: 'pdf', ageBand: '7-9' }; };
const persist = (s: State) => { try { const { busy, err, ...keep } = s; void busy; void err; sessionStorage.setItem(KEY, JSON.stringify(keep)); } catch { /* */ } };

const GOAL_COLORS = ['var(--sun)', 'var(--mint)', 'var(--sky)', 'var(--berry)', 'var(--coral)'];
const SOURCE_LABEL: Record<string, string> = { llm: 'Generated by AI', heuristic: 'Built offline (no AI key)', sample: 'Sample' };
const MAX_BYTES = 10 * 1024 * 1024;

export function renderLab(main: HTMLElement, worldId?: string) {
  main.className = 'lab';
  let S: State = load();
  let samples: Sample[] | null = null;
  let samplesErr = '';
  let forgeTimer = 0;
  let alive = true;

  const set = (patch: Partial<State>, rerender = true) => { S = { ...S, ...patch }; persist(S); if (rerender) draw(); };

  // ------------------------------------------------------------ actions
  async function useMaterial(p: Promise<Material>) {
    set({ busy: 'source', err: undefined, material: undefined, lesson: undefined, gen: undefined, world: undefined, template: undefined, dirty: false, savedDiag: undefined });
    focusSection('forge');
    try {
      const material = await p;
      if (!alive) return;
      set({ material, busy: undefined });
      await makeLesson();
    } catch (e) {
      set({ busy: undefined, err: { at: 'source', msg: friendly(e) } });
    }
  }

  async function makeLesson() {
    if (!S.material) return;
    set({ busy: 'lesson', err: undefined, gen: undefined, world: undefined });
    focusSection('forge');
    try {
      const r = await api.generateLesson(S.material.materialId, S.ageBand);
      if (!alive) return;
      set({ lesson: r.lesson, lessonSource: r.source, lessonDiag: r.diagnostics, template: r.lesson.suggestedTemplate, busy: undefined });
      focusSection('goals');
    } catch (e) {
      set({ busy: undefined, err: { at: 'lesson', msg: friendly(e), retry: makeLesson } });
    }
  }

  async function makeWorld() {
    if (!S.lesson) return;
    set({ busy: 'world', err: undefined, gen: undefined, world: undefined, savedDiag: undefined, dirty: false });
    focusSection('forge');
    try {
      const r = await api.generateWorld(S.lesson, S.template);
      if (!alive) return;
      set({ gen: r, world: r.world, busy: undefined });
      focusSection('world');
      setTimeout(() => confetti($('#world-h', main) ?? undefined), 150);
    } catch (e) {
      set({ busy: undefined, err: { at: 'world', msg: friendly(e), retry: makeWorld } });
    }
  }

  async function saveWorld() {
    if (!S.world) return;
    set({ busy: 'save', err: undefined }, false);
    const btn = $<HTMLButtonElement>('#save-btn', main);
    if (btn) { btn.disabled = true; btn.querySelector('span')!.textContent = 'Saving…'; }
    try {
      const r = await api.saveWorld(S.world);
      if (!alive) return;
      set({ world: r.world, gen: { ...r }, dirty: false, savedDiag: r.diagnostics, busy: undefined });
      toast(r.diagnostics.length ? `Saved. ${r.diagnostics.length} note${r.diagnostics.length > 1 ? 's' : ''} to check` : 'Saved');
    } catch (e) {
      set({ busy: undefined, err: { at: 'save', msg: friendly(e), retry: saveWorld } });
    }
  }

  function startOver() {
    try { sessionStorage.removeItem(KEY); } catch { /* */ }
    S = { tab: S.tab, ageBand: S.ageBand };
    if (location.hash !== '#lab') location.hash = '#lab'; else draw();
  }

  function focusSection(id: string) {
    requestAnimationFrame(() => {
      const el = $(`#sec-${id}`, main);
      if (!el) return;
      el.scrollIntoView({ behavior: reducedMotion() ? 'auto' : 'smooth', block: 'start' });
      const h = el.querySelector<HTMLElement>('h2,h3');
      h?.setAttribute('tabindex', '-1'); h?.focus({ preventScroll: true });
    });
  }

  // ------------------------------------------------------------ views
  const errBox = (at: NonNullable<State['err']>['at']) => S.err?.at === at ? `
    <div class="err" role="alert"><p>${esc(S.err.msg)}</p>${S.err.retry ? `<button class="btn btn-paper btn-sm" data-act="retry">${I.refresh}<span>Try again</span></button>` : ''}</div>` : '';

  function stepper() {
    const n = S.world ? 4 : S.lesson ? 3 : S.material ? 2 : 1;
    const steps = ['Add a lesson', 'Check the goals', 'Build a world', 'Play'];
    return `<ol class="stepper" aria-label="Progress">${steps.map((s, i) => `<li class="${i + 1 < n ? 'done' : i + 1 === n ? 'now' : ''}" ${i + 1 === n ? 'aria-current="step"' : ''}><span>${i + 1 < n ? I.check : i + 1}</span>${s}</li>`).join('')}</ol>`;
  }

  function sourceView() {
    if (S.material && S.busy !== 'source') {
      const m = S.material;
      return `<section class="panel done-panel" id="sec-source" aria-labelledby="src-h">
        <div class="row-between">
          <div><h2 id="src-h" class="h-sm">${I.file} ${esc(m.title)}</h2>
          <p class="meta">${m.kind === 'pdf' ? `PDF, ${m.pages} page${m.pages === 1 ? '' : 's'}` : m.kind === 'sample' ? 'Sample lesson' : 'Pasted text'}, ${m.chars.toLocaleString()} characters, ${m.sections.length} section${m.sections.length === 1 ? '' : 's'} found</p></div>
          <button class="btn btn-paper btn-sm" data-act="over">${I.refresh}<span>Use a different lesson</span></button>
        </div>
        <details class="sections"><summary>See the sections we read</summary><ol>${m.sections.map((s) => `<li><b>${esc(s.id)}</b> ${esc(s.heading)}</li>`).join('')}</ol></details>
      </section>`;
    }
    return `<section class="panel" id="sec-source" aria-labelledby="src-h">
      <h2 id="src-h" class="display h-md">Start with a lesson</h2>
      <p class="muted">A one or two page lesson works best. We read it and pull out three things to learn.</p>
      <div class="tabs" role="tablist" aria-label="Lesson source">
        <button role="tab" id="tab-pdf" aria-controls="tp-pdf" aria-selected="${S.tab === 'pdf'}" tabindex="${S.tab === 'pdf' ? 0 : -1}" data-tab="pdf">${I.upload}<span>Upload a PDF</span></button>
        <button role="tab" id="tab-text" aria-controls="tp-text" aria-selected="${S.tab === 'text'}" tabindex="${S.tab === 'text' ? 0 : -1}" data-tab="text">${I.text}<span>Paste text</span></button>
      </div>
      <div role="tabpanel" id="tp-pdf" aria-labelledby="tab-pdf" ${S.tab === 'pdf' ? '' : 'hidden'}>
        <label class="drop" id="drop">
          <input type="file" id="file" accept="application/pdf,.pdf" class="sr-only" />
          <span class="drop-art">${I.file}</span>
          <span class="drop-big">Drop a PDF here</span>
          <span class="drop-small">or <u>choose a file</u>. PDF only, up to 10 MB.</span>
        </label>
      </div>
      <div role="tabpanel" id="tp-text" aria-labelledby="tab-text" ${S.tab === 'text' ? '' : 'hidden'}>
        <form class="paste" id="paste">
          <label>Lesson title<input name="title" required maxlength="120" placeholder="e.g. How plants make food" /></label>
          <label>Lesson text<textarea name="text" required minlength="200" rows="9" placeholder="Paste a page or two of your lesson here"></textarea></label>
          <p class="hint-line" id="paste-count">At least 200 characters.</p>
          <button class="btn btn-sun" type="submit">${I.arrow}<span>Read this lesson</span></button>
        </form>
      </div>
      ${errBox('source')}
      <h3 class="h-sm samples-h">Or try a sample lesson</h3>
      <div class="samples" id="samples">${samplesView()}</div>
    </section>`;
  }

  function samplesView() {
    if (samples === null && !samplesErr) return `<p class="muted">Loading samples…</p>`;
    if (samplesErr) return `<div class="err soft"><p>Couldn't load samples. ${esc(samplesErr)}</p><a class="btn btn-paper btn-sm" href="/play.html?world=forest-plants">${I.play}<span>Play the demo</span></a></div>`;
    if (!samples!.length) return `<p class="muted">No sample lessons on this server.</p>`;
    return samples!.map((s) => {
      const w = worldMeta(s.templateId);
      return `<article class="sample" style="--accent:${w.accent}">
        <div class="sample-art">${thumb(s.templateId)}</div>
        <div class="sample-body">
          <h4>${esc(s.title)}</h4><p class="meta">${esc(w.name)}</p>
          <div class="sample-acts">
            <button class="btn btn-sun btn-sm" data-sample="${esc(s.id)}">${I.arrow}<span>Use this lesson</span></button>
            ${s.pdfUrl ? `<a class="btn btn-ghost btn-sm" href="${esc(s.pdfUrl)}" download>${I.download}<span>PDF</span></a>` : ''}
          </div>
        </div>
      </article>`;
    }).join('');
  }

  function forgeView() {
    const b = S.busy;
    if (!b || b === 'save') return '';
    const stages = b === 'source' ? ['Reading your lesson', 'Splitting it into sections']
      : b === 'lesson' ? ['Finding three things to learn', 'Matching each goal to a sentence in the lesson', 'Listing key ideas']
        : ['Writing study cards from your lesson', 'Laying out the places', 'Casting three characters', 'Writing checks, puzzles and side quests', 'Checking every answer against the lesson'];
    const t: TemplateId = b === 'world' ? (S.template ?? 'forest') : 'forest';
    return `<section class="panel forge" id="sec-forge" aria-labelledby="forge-h" aria-busy="true">
      <div class="forge-isle forging" style="--accent:${worldMeta(t).accent}">${thumb(t)}</div>
      <div>
        <h2 id="forge-h" class="display h-md">${b === 'world' ? `Building ${esc(worldMeta(t).name)}` : b === 'lesson' ? 'Finding the goals' : 'Reading the lesson'}</h2>
        <ol class="forge-steps" id="forge-steps">${stages.map((s, i) => `<li class="${i === 0 ? 'now' : ''}"><span class="dot"></span>${s}</li>`).join('')}</ol>
        <p class="muted small">${b === 'world' ? 'This can take up to a minute with AI.' : 'Usually a few seconds.'}</p>
      </div>
    </section>`;
  }

  function goalsView() {
    const L = S.lesson; if (!L) return '';
    const sec = (id: string) => L.sections.find((s) => s.id === id);
    return `<section class="panel" id="sec-goals" aria-labelledby="goals-h">
      <div class="row-between wrap">
        <div><h2 id="goals-h" class="display h-md">What kids will learn</h2>
        <p class="muted">${esc(L.summary)}</p></div>
        <div class="row-gap">
          <span class="badge src-${esc(S.lessonSource ?? '')}">${esc(SOURCE_LABEL[S.lessonSource ?? ''] ?? S.lessonSource ?? '')}</span>
          <fieldset class="seg"><legend class="sr-only">Age band</legend>
            ${(['7-9', '10-12'] as AgeBand[]).map((a) => `<label><input type="radio" name="age" value="${a}" ${S.ageBand === a ? 'checked' : ''}/><span>Ages ${a.replace('-', '–')}</span></label>`).join('')}
          </fieldset>
        </div>
      </div>
      <p class="hint-line">${I.pencil} Click any goal to reword it. Changes go into the world you build next.</p>
      <ol class="goals">
        ${L.objectives.map((o, i) => `<li class="goal" style="--c:${GOAL_COLORS[i % 5]}">
          <span class="goal-n" aria-hidden="true">${i + 1}</span>
          <div class="goal-body">
            <label class="sr-only" for="obj-${i}">Goal ${i + 1}</label>
            <textarea id="obj-${i}" class="inline-edit" rows="2" data-obj="${i}">${esc(o.text)}</textarea>
            ${o.evidence.map((e) => { const s = sec(e.sectionId); return `<blockquote class="cite"><span class="cite-src">From ${esc(e.sectionId)}${s ? `, “${esc(s.heading)}”` : ''}</span>“${esc(e.quote)}”</blockquote>`; }).join('')}
            <div class="chips">${o.conceptIds.map((c) => { const k = L.concepts.find((x) => x.id === c); return `<span class="chip">${esc(k?.name ?? c)}</span>`; }).join('')}</div>
            ${o.rubric?.criteria?.length ? `<details class="rubric"><summary>How the game checks this</summary><ul>${o.rubric.criteria.map((c) => `<li>${esc(c)}</li>`).join('')}</ul><p class="small muted">${esc(o.rubric.passingRule)}</p></details>` : ''}
          </div>
        </li>`).join('')}
      </ol>
      <h3 class="h-sm">Key ideas</h3>
      <div class="chips big">${L.concepts.map((c) => `<span class="chip" title="${esc(c.description)}">${esc(c.name)}</span>`).join('')}</div>
      ${S.lessonDiag?.length ? `<details class="diag"><summary>${S.lessonDiag.length} note${S.lessonDiag.length > 1 ? 's' : ''} from the goal finder</summary><ul>${S.lessonDiag.map((d) => `<li>${esc(d)}</li>`).join('')}</ul></details>` : ''}
      ${errBox('lesson')}
    </section>
    <section class="panel" id="sec-pick" aria-labelledby="pick-h">
      <h2 id="pick-h" class="display h-md">Pick a world</h2>
      <div class="pick" role="radiogroup" aria-labelledby="pick-h">
        ${WORLDS.map((w) => `<label class="pick-card ${S.template === w.id ? 'on' : ''}" style="--accent:${w.accent}">
          <input type="radio" name="tpl" value="${w.id}" ${S.template === w.id ? 'checked' : ''} class="sr-only"/>
          ${L.suggestedTemplate === w.id ? `<span class="best">Best fit</span>` : ''}
          <span class="pick-art">${thumb(w.id)}</span>
          <span class="pick-name">${esc(w.name)}</span>
        </label>`).join('')}
      </div>
      <div class="row-gap">
        <button class="btn btn-sun btn-lg" data-act="world" ${S.busy ? 'disabled' : ''}>${I.map}<span>${S.world ? 'Build it again' : `Build ${esc(worldMeta(S.template ?? L.suggestedTemplate).name)}`}</span></button>
      </div>
      ${errBox('world')}
    </section>`;
  }

  function qEditor(q: Question, path: string, label: string) {
    return `<fieldset class="qedit"><legend>${esc(label)}</legend>
      <label>Question<input data-path="${path}.prompt" value="${esc(q.prompt)}"/></label>
      <div class="choices" role="group" aria-label="Choices; pick the correct one">
        ${q.choices.map((c, i) => `<div class="choice ${i === q.answerIndex ? 'right' : ''}">
          <input type="radio" name="${path}" id="${path}-r${i}" data-path="${path}.answerIndex" value="${i}" ${i === q.answerIndex ? 'checked' : ''} aria-label="Mark choice ${i + 1} correct"/>
          <label for="${path}-r${i}" class="tick">${I.check}</label>
          <input data-path="${path}.choices.${i}" value="${esc(c)}" aria-label="Choice ${i + 1}"/>
        </div>`).join('')}
      </div>
      <label>Also accept when spoken <span class="muted small">(comma separated)</span><input data-path="${path}.accept" data-list="1" value="${esc(q.accept.join(', '))}"/></label>
      ${q.explain ? `<p class="small muted">After answering: ${esc(q.explain)}</p>` : ''}
    </fieldset>`;
  }

  function mapView(w: WorldSpec) {
    const spots: [number, number][] = [[0, 0.05], [-0.62, -0.35], [0.55, -0.45], [-0.25, 0.62], [0.05, -0.85], [0.68, 0.42]];
    const order = [...w.zones].sort((a, b) => ['hub', 'landmark', 'wild', 'goal'].indexOf(a.kind) - ['hub', 'landmark', 'wild', 'goal'].indexOf(b.kind));
    const pos = (z: Zone, i: number): [number, number] => {
      if (z.kind === 'hub') return iso(...spots[0]);
      if (z.kind === 'goal') return iso(...spots[4]);
      const others = order.filter((x) => x.kind !== 'hub' && x.kind !== 'goal');
      const k = others.indexOf(z); void i;
      return iso(...[spots[1], spots[2], spots[3], spots[5]][k % 4]);
    };
    const pins = order.map((z, i) => { const [x, y] = pos(z, i); return { z, x, y, n: i + 1 }; });
    const hub = pins.find((p) => p.z.kind === 'hub');
    return `<div class="mapwrap">
      <svg class="zone-map" viewBox="0 -20 400 320" role="img" aria-label="Map of ${esc(w.title)}">
        <g opacity=".95">${islandSVG(w.templateId, { bare: true }).replace(/^<svg[^>]*>|<\/svg>$/g, '')}</g>
        ${hub ? pins.filter((p) => p !== hub).map((p) => `<path d="M${hub.x} ${hub.y} L${p.x} ${p.y}" stroke="var(--paper)" stroke-width="5" stroke-dasharray="1 9" stroke-linecap="round"/>`).join('') : ''}
        ${pins.map((p) => `<g class="pin pin-${p.z.kind}"><path d="M${p.x} ${p.y} l-11 -18 a13 13 0 1 1 22 0 Z" fill="${p.z.kind === 'goal' ? 'var(--berry)' : p.z.kind === 'hub' ? 'var(--paper)' : 'var(--sun)'}" stroke="var(--ink)" stroke-width="3" stroke-linejoin="round"/><text x="${p.x}" y="${p.y - 22}" text-anchor="middle" font-family="Jersey 10" font-size="18" fill="var(--ink)">${p.n}</text></g>`).join('')}
      </svg>
      <ol class="zone-list">${pins.map((p) => { const o = S.world!.npcs.find((n) => n.zoneId === p.z.id); return `<li><span class="zn zn-${p.z.kind}">${p.n}</span><div><b>${esc(p.z.name)}</b> <span class="kind">${p.z.kind === 'hub' ? 'start' : p.z.kind === 'goal' ? 'finale' : p.z.kind === 'landmark' ? 'memory spot' : 'wild'}</span><p>${esc(p.z.description)}${o ? ` <span class="muted">${esc(o.name)} lives here.</span>` : ''}</p></div></li>`; }).join('')}</ol>
    </div>`;
  }

  function worldView() {
    const w = S.world; if (!w) return '';
    const g = S.gen;
    const meta = worldMeta(w.templateId);
    const link = new URL(playUrl(w.worldId), location.href).href;
    const objText = (id: string) => (S.lesson?.objectives.find((o) => o.id === id)?.text) ?? id;
    const diag = S.savedDiag ?? g?.diagnostics ?? [];
    const objIds = S.lesson?.objectives.map((o) => o.id) ?? [...new Set(w.npcs.map((n) => n.objectiveId))];
    const objNum = (id: string) => Math.max(0, objIds.indexOf(id)) + 1;
    return `<section class="panel world-panel" id="sec-world" aria-labelledby="world-h" style="--accent:${meta.accent}">
      <div class="world-top">
        <div class="world-art">${thumb(w.templateId, meta.name + ' island')}</div>
        <div>
          <p class="badges"><span class="badge src-${esc(w.source)}">${esc(SOURCE_LABEL[w.source] ?? w.source)}</span><span class="badge plain">${esc(meta.name)}</span><span class="badge plain">${esc(w.subject)}</span>
          ${g?.fallback ? `<span class="badge warn">Used the backup builder</span>` : ''}${g?.repaired ? `<span class="badge warn">Auto-fixed</span>` : ''}</p>
          <h2 id="world-h" class="display h-lg">${esc(w.title)}</h2>
          ${w.story.intro.map((p) => `<p>${esc(p)}</p>`).join('')}
          <p class="goalline"><b>The quest:</b> ${esc(w.story.goal)}</p>
          <div class="play-row">
            <a class="btn btn-sun btn-xl" href="${esc(playUrl(w.worldId))}">${I.play}<span>Play this world</span></a>
            <div class="copy">
              <label class="sr-only" for="share">Link to this world</label>
              <input id="share" readonly value="${esc(link)}"/>
              <button class="btn btn-paper btn-sm" data-act="copy">${I.link}<span>Copy link</span></button>
            </div>
          </div>
          ${S.dirty ? `<p class="small warn-text">You have unsaved changes. Save them before playing.</p>` : ''}
        </div>
      </div>
      ${diag.length ? `<details class="diag" ${S.savedDiag ? 'open' : ''}><summary>${diag.length} check${diag.length > 1 ? 's' : ''} from the world validator</summary><ul>${diag.map((d) => `<li>${esc(d)}</li>`).join('')}</ul></details>` : ''}

      <h3 class="h-sm">${I.map} Places</h3>
      ${mapView(w)}

      <h3 class="h-sm">${I.book} Study cards</h3>
      <p class="hint-line">This is what kids read at each place before they talk to anyone. Keep it short and true to your lesson.</p>
      <div class="studies">
        ${(w.study ?? []).map((c, i) => { const z = w.zones.find((x) => x.id === c.zoneId); const n = objNum(c.objectiveId); return `<article class="study" style="--c:${GOAL_COLORS[(n - 1) % 5]}">
          <header><span class="goal-tag">Goal ${n}</span><span class="muted small">${z ? `At ${esc(z.name)}` : ''}${c.sourceSectionIds?.length ? `. From your lesson: ${c.sourceSectionIds.map(esc).join(', ')}` : ''}</span></header>
          <label class="title-edit"><span class="sr-only">Card title</span><input data-path="study.${i}.title" value="${esc(c.title)}"/></label>
          ${c.body.map((b, k) => `<label><span class="sr-only">Paragraph ${k + 1}</span><textarea class="fit" rows="2" data-path="study.${i}.body.${k}">${esc(b)}</textarea></label>`).join('')}
          ${c.keyTerms?.length ? `<fieldset class="terms"><legend>Key words</legend>${c.keyTerms.map((t, k) => `<div class="term"><input data-path="study.${i}.keyTerms.${k}.term" value="${esc(t.term)}" aria-label="Key word ${k + 1}"/><input data-path="study.${i}.keyTerms.${k}.meaning" value="${esc(t.meaning)}" aria-label="Meaning of key word ${k + 1}"/></div>`).join('')}</fieldset>` : ''}
          ${c.example !== undefined ? `<label>Example<textarea class="fit" rows="2" data-path="study.${i}.example">${esc(c.example)}</textarea></label>` : ''}
          ${(c.checks ?? []).map((q, k) => qEditor(q, `study.${i}.checks.${k}`, `Quick check ${k + 1}`)).join('')}
        </article>`; }).join('') || `<p class="muted">This world has no study cards yet. Rebuild it to add them.</p>`}
      </div>

      <h3 class="h-sm">${I.chat} Characters</h3>
      <div class="npcs">
        ${w.npcs.map((n, i) => `<article class="npc">
          <header><span class="npc-face" aria-hidden="true" style="--h:${i * 90}"></span><div><h4>${esc(n.name)} <span class="muted">${esc(n.title)}</span></h4><span class="badge plain">${esc(n.archetype)}</span></div></header>
          <p class="bub npc">${esc(n.greeting)}</p>
          <p class="small"><b>Teaches goal ${objNum(n.objectiveId)}:</b> ${esc(objText(n.objectiveId))}</p>
          <p class="small muted">After the check question, kids explain this goal to ${esc(n.name)} in their own words.</p>
          ${qEditor(n.check, `npcs.${i}.check`, `${n.name}'s check question`)}
        </article>`).join('')}
      </div>

      <h3 class="h-sm">${I.hint} Puzzles and answer keys</h3>
      <p class="hint-line">Only you see the answers. Edit anything, then save.</p>
      <div class="puzzles">
        ${w.puzzles.map((p, i) => `<article class="puzzle">
          <header><h4>${esc(p.title)}</h4><span class="badge plain">${p.kind === 'sequence' ? 'Put in order' : p.kind === 'match' ? 'Match pairs' : 'Choose the answer'}</span></header>
          <label>What the puzzle says<input data-path="puzzles.${i}.prompt" value="${esc(p.prompt)}"/></label>
          ${p.kind === 'sequence' && p.items ? `<fieldset class="qedit"><legend>Correct order</legend><ol class="seq">${p.items.map((it, k) => `<li><input data-path="puzzles.${i}.items.${k}" value="${esc(it)}" aria-label="Step ${k + 1}"/></li>`).join('')}</ol></fieldset>` : ''}
          ${p.kind === 'match' && p.pairs ? `<fieldset class="qedit"><legend>Pairs that belong together</legend>${p.pairs.map((pr, k) => `<div class="pair"><input data-path="puzzles.${i}.pairs.${k}.left" value="${esc(pr.left)}" aria-label="Pair ${k + 1} left"/><span aria-hidden="true">${I.link}</span><input data-path="puzzles.${i}.pairs.${k}.right" value="${esc(pr.right)}" aria-label="Pair ${k + 1} right"/></div>`).join('')}</fieldset>` : ''}
          ${p.kind === 'choice' && p.questions ? p.questions.map((q, k) => qEditor(q, `puzzles.${i}.questions.${k}`, `Question ${k + 1}`)).join('') : ''}
          <p class="small muted">Grounded in ${p.evidenceSectionIds.map(esc).join(', ') || 'the lesson'}.</p>
        </article>`).join('')}
      </div>

      ${(w.sideQuests ?? []).length ? `<h3 class="h-sm">${I.arrow} Side quests</h3>
      <p class="hint-line">Optional extra practice kids can pick up from characters.</p>
      <div class="puzzles">
        ${w.sideQuests.map((q, i) => { const giver = w.npcs.find((n) => n.id === q.giverNpcId); return `<article class="puzzle">
          <header><h4>${esc(q.title)}</h4><span class="badge plain">${q.kind === 'explain' ? 'Explain it' : q.kind === 'find' ? 'Find and answer' : 'Extra quiz'}</span></header>
          <p class="small muted">From ${esc(giver?.name ?? q.giverNpcId)}, goal ${objNum(q.objectiveId)}. Reward: ${esc(q.reward)}</p>
          <label>What they ask<textarea class="fit" rows="2" data-path="sideQuests.${i}.prompt">${esc(q.prompt)}</textarea></label>
          ${q.rubric?.length ? `<label>A good answer mentions <span class="muted small">(comma separated)</span><input data-path="sideQuests.${i}.rubric" data-list="1" value="${esc(q.rubric.join(', '))}"/></label>` : ''}
          ${(q.questions ?? []).map((qq, k) => qEditor(qq, `sideQuests.${i}.questions.${k}`, `Question ${k + 1}`)).join('')}
        </article>`; }).join('')}
      </div>` : ''}

      <h3 class="h-sm">${I.pin} Memory finale</h3>
      <p class="hint-line">At the end, kids walk back to each memory spot and answer from memory, with no answers on screen.</p>
      <div class="puzzles">
        ${w.memoryLandmarks.map((m, i) => { const z = w.zones.find((x) => x.id === m.zoneId); return `<article class="puzzle">${qEditor(m.question, `memoryLandmarks.${i}.question`, `At ${z?.name ?? m.zoneId}`)}</article>`; }).join('')}
      </div>

      ${(w.glossary ?? []).length ? `<h3 class="h-sm">${I.book} Study book</h3>
      <p class="hint-line">Every key word, collected in the book kids carry in the game.</p>
      <dl class="glossary">${w.glossary.map((g) => `<div><dt>${esc(g.term)}</dt><dd>${esc(g.meaning)} <span class="muted small">${esc(g.sectionId)}</span></dd></div>`).join('')}</dl>` : ''}

      <div class="savebar ${S.dirty ? 'show' : ''}">
        <p>${S.dirty ? 'Unsaved changes' : 'All changes saved'}</p>
        <button class="btn btn-sun" id="save-btn" data-act="save" ${S.dirty ? '' : 'disabled'}>${I.save}<span>Save changes</span></button>
      </div>
      ${errBox('save')}
    </section>`;
  }

  function draw() {
    main.innerHTML = `
      <div class="lab-head">
        <div><p class="badges"><span class="badge src-sample">Coming next</span></p><h1 class="display h-lg">Make your own world</h1><p class="muted">Upload a lesson and we build a world from it. Check what the characters will teach, then share one link. This is an early preview.</p></div>
        ${S.material || S.world ? `<button class="btn btn-ghost btn-sm" data-act="over">${I.refresh}<span>Start over</span></button>` : ''}
      </div>
      ${stepper()}
      <div class="flow">
        ${S.busy === 'source' ? '' : sourceView()}
        ${S.busy === 'source' || S.busy === 'lesson' ? forgeView() : ''}
        ${S.busy === 'lesson' ? '' : goalsView()}
        ${S.busy === 'world' ? forgeView() : worldView()}
      </div>`;
    wire();
    runForge();
    hydrateThumbs(main);
  }

  function runForge() {
    clearInterval(forgeTimer);
    const list = $$('#forge-steps li', main);
    if (!list.length) return;
    let i = 0;
    forgeTimer = window.setInterval(() => {
      if (i >= list.length - 1) { clearInterval(forgeTimer); return; }
      list[i].className = 'done'; i++; list[i].className = 'now';
    }, S.busy === 'world' ? 4200 : 1400);
  }

  // ------------------------------------------------------------ events
  function setPath(obj: any, path: string, value: unknown) {
    const keys = path.split('.');
    let o = obj;
    for (let k = 0; k < keys.length - 1; k++) o = o[/^\d+$/.test(keys[k]) ? Number(keys[k]) : keys[k]];
    o[keys[keys.length - 1]] = value;
  }

  function markDirty() {
    if (!S.dirty) {
      S.dirty = true;
      $('.savebar', main)?.classList.add('show');
      const p = $('.savebar p', main); if (p) p.textContent = 'Unsaved changes';
      const b = $<HTMLButtonElement>('#save-btn', main); if (b) b.disabled = false;
    }
    persist(S);
  }

  function handleFile(f: File | undefined) {
    if (!f) return;
    const isPdf = f.type === 'application/pdf' || /\.pdf$/i.test(f.name);
    if (!isPdf) { set({ err: { at: 'source', msg: `“${f.name}” isn't a PDF. Upload a PDF, or paste the text instead.` } }); return; }
    if (f.size > MAX_BYTES) { set({ err: { at: 'source', msg: `That PDF is ${(f.size / 1048576).toFixed(1)} MB. The limit is 10 MB.` } }); return; }
    useMaterial(api.uploadPdf(f));
  }

  function wire() {
    // tabs with arrow-key support
    const tabs = $$<HTMLButtonElement>('[role=tab]', main);
    tabs.forEach((t, i) => {
      t.addEventListener('click', () => set({ tab: t.dataset.tab as SourceTab, err: undefined }));
      t.addEventListener('keydown', (e) => {
        if (e.key !== 'ArrowRight' && e.key !== 'ArrowLeft') return;
        const n = tabs[(i + (e.key === 'ArrowRight' ? 1 : tabs.length - 1)) % tabs.length];
        set({ tab: n.dataset.tab as SourceTab }); $<HTMLButtonElement>(`#tab-${n.dataset.tab}`, main)?.focus();
      });
    });
    const drop = $('#drop', main);
    if (drop) {
      const file = $<HTMLInputElement>('#file', main)!;
      file.addEventListener('change', () => handleFile(file.files?.[0]));
      ['dragenter', 'dragover'].forEach((ev) => drop.addEventListener(ev, (e) => { e.preventDefault(); drop.classList.add('over'); }));
      ['dragleave', 'drop'].forEach((ev) => drop.addEventListener(ev, () => drop.classList.remove('over')));
      drop.addEventListener('drop', (e) => { e.preventDefault(); handleFile((e as DragEvent).dataTransfer?.files?.[0]); });
    }
    const paste = $<HTMLFormElement>('#paste', main);
    if (paste) {
      const ta = paste.elements.namedItem('text') as HTMLTextAreaElement;
      ta.addEventListener('input', () => { $('#paste-count', main)!.textContent = `${ta.value.length.toLocaleString()} characters${ta.value.length < 200 ? ', at least 200 needed' : ''}.`; });
      paste.addEventListener('submit', (e) => {
        e.preventDefault();
        const fd = new FormData(paste);
        useMaterial(api.uploadText(String(fd.get('title')).trim(), String(fd.get('text')).trim()));
      });
    }
    $$<HTMLButtonElement>('[data-sample]', main).forEach((b) => b.addEventListener('click', () => useMaterial(api.sample(b.dataset.sample!))));
    $$<HTMLButtonElement>('[data-act]', main).forEach((b) => b.addEventListener('click', (e) => {
      const a = b.dataset.act;
      if (a === 'over') startOver();
      else if (a === 'world') makeWorld();
      else if (a === 'save') saveWorld();
      else if (a === 'retry') S.err?.retry?.();
      else if (a === 'copy') {
        const v = ($<HTMLInputElement>('#share', main))!.value;
        navigator.clipboard?.writeText(v).then(() => toast('Link copied'), () => { $<HTMLInputElement>('#share', main)!.select(); toast('Press Ctrl+C to copy', 'warn'); });
        e.preventDefault();
      }
    }));
    // age band regenerate
    $$<HTMLInputElement>('input[name=age]', main).forEach((r) => r.addEventListener('change', () => { S.ageBand = r.value as AgeBand; makeLesson(); }));
    // objective edits
    $$<HTMLTextAreaElement>('[data-obj]', main).forEach((t) => {
      const fit = () => { t.style.height = 'auto'; t.style.height = `${t.scrollHeight}px`; };
      fit();
      t.addEventListener('input', () => { fit(); if (S.lesson) { S.lesson.objectives[Number(t.dataset.obj)].text = t.value; persist(S); } });
    });
    // template pick
    $$<HTMLInputElement>('input[name=tpl]', main).forEach((r) => r.addEventListener('change', () => {
      S.template = r.value as TemplateId; persist(S);
      $$('.pick-card', main).forEach((c) => c.classList.toggle('on', c.contains(r)));
      const btn = $('[data-act=world] span', main); if (btn) btn.textContent = S.world ? 'Build it again' : `Build ${worldMeta(S.template).name}`;
    }));
    // world edits
    $$<HTMLInputElement>('[data-path]', main).forEach((inp) => {
      if (inp.classList.contains('fit')) { const fit = () => { inp.style.height = 'auto'; inp.style.height = `${inp.scrollHeight}px`; }; fit(); inp.addEventListener('input', fit); }
      const ev = inp.type === 'radio' ? 'change' : 'input';
      inp.addEventListener(ev, () => {
        if (!S.world) return;
        const v = inp.type === 'radio' ? Number(inp.value) : inp.dataset.list ? inp.value.split(',').map((s) => s.trim()).filter(Boolean) : inp.value;
        setPath(S.world, inp.dataset.path!, v);
        if (inp.type === 'radio') inp.closest('.choices')?.querySelectorAll('.choice').forEach((c) => c.classList.toggle('right', c.contains(inp)));
        markDirty();
      });
    });
  }

  // ------------------------------------------------------------ boot
  draw();
  api.samples().then((s) => { samples = s; }, (e) => { samplesErr = friendly(e); }).finally(() => {
    if (!alive) return;
    const box = $('#samples', main);
    if (box) { box.innerHTML = samplesView(); hydrateThumbs(box); $$<HTMLButtonElement>('[data-sample]', box).forEach((b) => b.addEventListener('click', () => useMaterial(api.sample(b.dataset.sample!)))); }
  });
  if (worldId && S.world?.worldId !== worldId) {
    api.world(worldId).then((w) => {
      if (!alive) return;
      S = { tab: 'pdf', ageBand: '7-9', world: w, template: w.templateId, gen: { world: w, diagnostics: [], repaired: false, fallback: false } };
      persist(S); draw(); focusSection('world');
    }, (e) => toast(`Couldn't open that world. ${friendly(e)}`, 'warn'));
  }

  return () => { alive = false; clearInterval(forgeTimer); };
}
